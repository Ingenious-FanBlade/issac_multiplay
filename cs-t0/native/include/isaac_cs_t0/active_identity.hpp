[[nodiscard]] constexpr bool ApprovedIdentity(
    const std::array<std::uint8_t, 32>& canonical_target,
    const std::array<std::uint8_t, 32>& observed_target,
    const std::array<std::uint8_t, 32>& target_equivalence,
    const std::array<std::uint8_t, 32>& mode_gate,
    const std::array<std::uint8_t, 32>& loop_gate,
    const std::array<std::uint8_t, 32>& raw_prerequisite,
    const std::array<std::uint8_t, 32>& catalog,
    const std::array<std::uint8_t, 32>& plan,
    const std::array<std::uint8_t, 32>& script) noexcept
{
    return canonical_target == kCanonicalTargetSha256 &&
           observed_target == kObservedUnpackedTargetSha256 &&
           target_equivalence == kTargetEquivalenceSha256 &&
           mode_gate == kModeGateSha256 && loop_gate == kLoopGateSha256 &&
           raw_prerequisite == kRawPrerequisiteSha256 &&
           catalog == kCatalogSha256 && plan == kPlanSha256 &&
           script == kScriptSha256;
}

[[nodiscard]] constexpr bool ApprovedProcessIdentity(
    std::uint32_t expected_pid,
    std::uint32_t current_pid,
    std::uint64_t expected_creation_time_100ns,
    std::uint64_t current_creation_time_100ns) noexcept
{
    return expected_pid != 0 && expected_pid == current_pid &&
           expected_creation_time_100ns != 0 &&
           expected_creation_time_100ns == current_creation_time_100ns;
}

